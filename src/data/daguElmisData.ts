// Ethiopian National IPLS Standard Resupply Calculation Helpers
export const daguIPLSFormulas = {
  // AMC = Quantity Dispensed / (Months in review period - Days out of stock / 30.5)
  calculateAMC: (quantityDispensed: number, reviewMonths = 2, daysOutOfStock = 0): number => {
    const effectiveMonths = Math.max(0.2, reviewMonths - (daysOutOfStock / 30.5));
    return Math.round((quantityDispensed / effectiveMonths) * 10) / 10;
  },

  // Months of Stock (MOS) = Stock on Hand / AMC
  calculateMOS: (stockOnHand: number, amc: number): number => {
    if (amc <= 0) return 0;
    return Math.round((stockOnHand / amc) * 10) / 10;
  },

  // Maximum Stock Quantity = Max MOS (4 months for facility) * AMC
  calculateMaxStock: (amc: number, maxMOS = 4): number => {
    return Math.round(amc * maxMOS);
  },

  // Minimum Stock Level = Min MOS (2 months for facility) * AMC
  calculateMinStock: (amc: number, minMOS = 2): number => {
    return Math.round(amc * minMOS);
  },

  // Suggested Order Quantity (SOQ) = Max Stock - (Stock on Hand + Pipeline) + Adjustments
  calculateSuggestedOrder: (maxStock: number, stockOnHand: number, pipeline = 0): number => {
    return Math.max(0, maxStock - (stockOnHand + pipeline));
  }
};
